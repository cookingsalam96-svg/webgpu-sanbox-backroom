"""Evidence classes are epistemic labels, not numeric confidence levels."""
from enum import Enum

class EvidenceClass(str, Enum):
    E1 = "E1"  # experimentally verified in cited source; must be independently sourced
    E2 = "E2"  # mathematically derived with reproducible derivation
    E3 = "E3"  # engineering analogy / design mapping
    E4 = "E4"  # unverified hypothesis
    E5 = "E5"  # generated by simulation


def validate_evidence_class(value, data_kind=None):
    try:
        evidence = EvidenceClass(value)
    except (ValueError, TypeError):
        raise ValueError("evidence_class must be one of E1, E2, E3, E4, E5")
    if evidence is EvidenceClass.E5 and data_kind not in (None, "simulation"):
        raise ValueError("E5 simulated evidence must have data_kind='simulation'")
    if data_kind == "simulation" and evidence is not EvidenceClass.E5:
        raise ValueError("simulation data must use evidence_class E5")
    return evidence
